"""Publication refuses a package set with a depend that no repository meets.

One unmet depend stops the whole pacman -Syu: alarm-aurora#404's linux-aurora
needs avd-fw>=0.1.aurora4, and a feed that carried it beside the older avd-fw
would hold back every update on the fleet.
"""
import importlib.util
import io
from pathlib import Path
import re
import subprocess
import sys
import tarfile
import tempfile
import unittest

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / 'scripts/check-feed-depends.py'
spec = importlib.util.spec_from_file_location('check_feed_depends', SCRIPT)
check = importlib.util.module_from_spec(spec)
spec.loader.exec_module(check)

KERNEL = check.Package('linux-aurora', '7.3.0.aurora1-41', [
    'coreutils', 'kmod', 'initramfs', 'aura>=1.0.0b12', 'avd-fw>=0.1.aurora4', 'aurora-stage2-trial'])
AURA = check.Package('aura', '1.0.0b14-1')
TRIAL = check.Package('asahi-scripts', '20260127.1-2', provides=['aurora-stage2-ctxr-slot=1', 'aurora-stage2-trial=1'])
UPSTREAM = [check.Package('coreutils', '9.9-1', ['glibc']), check.Package('glibc', '2.42-1'),
            check.Package('kmod', '34.2-1'), check.Package('mkinitcpio', '40-1', provides=['initramfs'])]


def tar(members, mode='w:gz'):
    data = io.BytesIO()
    with tarfile.open(fileobj=data, mode=mode) as archive:
        for name, text in members.items():
            info = tarfile.TarInfo(name)
            info.size = len(text.encode())
            archive.addfile(info, io.BytesIO(text.encode()))
    return data.getvalue()


def section(key, values):
    return f'%{key}%\n' + ''.join(f'{value}\n' for value in values) + '\n' if values else ''


def database(packages, split=False):
    """A pacman database; split puts %DEPENDS% and %PROVIDES% in a depends
    file, as Arch Linux ARM's databases do."""
    members = {}
    for package in packages:
        entry = f'{package.name}-{package.version}'
        desc = section('NAME', [package.name]) + section('VERSION', [package.version])
        relations = section('DEPENDS', package.depends) + section('PROVIDES', package.provides)
        if split:
            members[f'{entry}/desc'], members[f'{entry}/depends'] = desc, relations
        else:
            members[f'{entry}/desc'] = desc + relations
    return tar(members)


def package_archive(directory, package, compression='xz'):
    """A package archive whose .PKGINFO comes first, as makepkg writes it.
    Aurora's builds are .pkg.tar.xz; .zst is pacman's default."""
    lines = [f'pkgname = {package.name}', f'pkgver = {package.version}',
             *(f'depend = {d}' for d in package.depends), *(f'provides = {p}' for p in package.provides)]
    members = {'.PKGINFO': '# Generated by makepkg\n' + '\n'.join(lines) + '\n', '.MTREE': 'x'}
    # CI artifact names spell an epoch's ':' as '_'.
    path = directory / f'{package.name}-{package.version.replace(":", "_")}-aarch64.pkg.tar.{compression}'
    if compression == 'zst':
        archive = tar(members, mode='w')
        path.write_bytes(subprocess.run(['zstd', '-q', '-c'], input=archive, capture_output=True, check=True).stdout)
    else:
        path.write_bytes(tar(members, mode='w:xz'))
    return path


class DependsTests(unittest.TestCase):
    def unmet(self, candidates, upstream=UPSTREAM):
        return [(package.name, text) for package, text, _ in check.unmet(candidates, upstream)]

    def test_a_kernel_whose_avd_fw_floor_the_set_does_not_meet_is_refused(self):
        self.assertEqual(self.unmet([KERNEL, AURA, TRIAL, check.Package('avd-fw', '0.1.aurora3-1')]),
                         [('linux-aurora', 'avd-fw>=0.1.aurora4')])

    def test_the_kernel_passes_beside_the_avd_fw_it_needs(self):
        # The depend names no pkgrel, so the package's pkgrel is not compared.
        self.assertEqual(self.unmet([KERNEL, AURA, TRIAL, check.Package('avd-fw', '0.1.aurora4-1')]), [])

    def test_a_depend_nothing_carries_is_refused(self):
        self.assertEqual(self.unmet([KERNEL, AURA, TRIAL]), [('linux-aurora', 'avd-fw>=0.1.aurora4')])
        self.assertEqual(self.unmet([KERNEL, AURA, TRIAL, check.Package('avd-fw', '0.1.aurora4-1')], upstream=[]),
                         [('linux-aurora', 'coreutils'), ('linux-aurora', 'kmod'), ('linux-aurora', 'initramfs')])

    def test_provides_follow_pacman(self):
        def met(depend, *provides):
            return check.satisfies(check.Package('provider', '1-1', provides=provides), check.parse(depend))
        self.assertTrue(met('aurora-stage2-trial', 'aurora-stage2-trial=1'))
        self.assertTrue(met('aurora-stage2-trial>=1', 'aurora-stage2-trial=1'))
        self.assertTrue(met('initramfs', 'initramfs'))
        # An unversioned provides meets only an unversioned depend.
        self.assertFalse(met('initramfs>=1', 'initramfs'))
        # A library soname bump: libspandsp.so=4 does not meet a build linked to 2.
        self.assertFalse(met('libspandsp.so=2-64', 'libspandsp.so=4-64'))
        self.assertTrue(met('libspandsp.so=4-64', 'libspandsp.so=4-64'))

    def test_versions_compare_with_pacman_rules(self):
        avd = check.Package('avd-fw', '0.1.aurora4-1')
        for depend, expected in [('avd-fw>=0.1.aurora4', True), ('avd-fw>0.1.aurora4', False),
                                 ('avd-fw=0.1.aurora4', True), ('avd-fw=0.1.aurora4-2', False),
                                 ('avd-fw<0.1.aurora5', True), ('avd-fw<=0.1.aurora3', False),
                                 ('avd-fw>=0.1.aurora10', False), ('avd-fw', True)]:
            self.assertEqual(check.satisfies(avd, check.parse(depend)), expected, depend)
        self.assertTrue(check.satisfies(check.Package('pipewire', '1:1.6.10-1.6'), check.parse('pipewire>=1.7')))

    def test_both_database_layouts_and_package_archives_are_read(self):
        packages = [TRIAL, check.Package('coreutils', '9.9-1', ['glibc', 'acl'], ['coreutils-bin=9.9'])]
        for split in (False, True):
            read = {p.name: (p.version, p.depends, p.provides)
                    for p in check.database_packages(database(packages, split), 'core')}
            self.assertEqual(read, {p.name: (p.version, p.depends, p.provides) for p in packages})
        pipewire = check.Package('pipewire-audio', '1:1.6.10-1.6', ['libspandsp.so=2-64'], ['pipewire-audio=1.6.10'])
        for compression in ('xz', 'zst'):
            with tempfile.TemporaryDirectory() as tmp:
                package_archive(Path(tmp), KERNEL, compression)
                package_archive(Path(tmp), pipewire, compression)
                (Path(tmp) / f'linux-aurora-7.3.0.aurora1-41-aarch64.pkg.tar.{compression}.sig').write_bytes(b'sig')
                read = {(p.name, p.version, tuple(p.depends), tuple(p.provides))
                        for p in check.archive_packages(tmp, 'aurora')}
            self.assertEqual(read, {(p.name, p.version, tuple(p.depends), tuple(p.provides)) for p in (KERNEL, pipewire)})


class CommandTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.packages = self.root / 'input-packages'
        self.packages.mkdir()
        self.upstream = self.root / 'core.db'
        self.upstream.write_bytes(database(UPSTREAM, split=True))

    def run_check(self):
        return subprocess.run([sys.executable, str(SCRIPT), '--new', str(self.packages),
                               '--upstream', f'core={self.upstream}'], capture_output=True, text=True)

    def test_red_then_green(self):
        for package in (KERNEL, AURA, TRIAL, check.Package('avd-fw', '0.1.aurora3-1')):
            package_archive(self.packages, package)
        red = self.run_check()
        self.assertNotEqual(red.returncode, 0)
        self.assertIn('UNMET linux-aurora 7.3.0.aurora1-41 depends on avd-fw>=0.1.aurora4; '
                      'available: avd-fw 0.1.aurora3-1 [aurora]', red.stdout)
        self.assertIn('pacman -Syu would stop', red.stderr)
        (self.packages / 'avd-fw-0.1.aurora3-1-aarch64.pkg.tar.xz').unlink()
        package_archive(self.packages, check.Package('avd-fw', '0.1.aurora4-1'))
        green = self.run_check()
        self.assertEqual(green.returncode, 0, green.stdout + green.stderr)
        self.assertIn('Every depend of the 4 packages is met by the set or core', green.stdout)

    def test_an_empty_set_is_refused(self):
        result = self.run_check()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('No packages in', result.stderr)


class WiringTests(unittest.TestCase):
    def test_every_publication_checks_the_collected_set_before_it_is_bundled(self):
        workflow = (ROOT / '.github/workflows/publish.yml').read_text()
        collect = re.split(r'\n  [A-Za-z0-9_-]+:\n', workflow.split('\n  collect:\n', 1)[1], maxsplit=1)[0]
        steps = collect.split('\n      - ')
        index = next(i for i, step in enumerate(steps) if 'scripts/check-feed-depends.py' in step)
        names = [step.split('\n', 1)[0] for step in steps]
        self.assertLess(names.index('id: versions'), index)
        self.assertLess(index, names.index('id: bundle'))
        self.assertIn("if: steps.versions.outputs.status != 'unchanged'", steps[index])
        self.assertIn('python3 scripts/check-feed-depends.py --new input-packages', steps[index])
        self.assertNotIn('continue-on-error', steps[index])
        self.assertIn('mv input-packages ', steps[names.index('id: bundle')])

    def test_upstream_repositories_are_the_ones_the_image_configures(self):
        # build-image writes the Aurora sections with edgelib.add_sections.
        self.assertIn('edgelib.add_sections(', (ROOT / 'scripts/build-image').read_text())
        sections = (ROOT / 'scripts/edgelib.py').read_text()
        server = re.search(r'\[asahi-alarm\]\\nServer = ([^\\]+)\\n', sections).group(1)
        self.assertEqual(check.UPSTREAM['asahi-alarm'], server.replace('$arch', 'aarch64') + '/asahi-alarm.db')
        # [aurora-edge], [aurora] and [asahi-alarm] go before Arch Linux ARM's own repositories.
        self.assertIn("at = text.index('[core]')", sections)
        self.assertEqual(list(check.UPSTREAM), ['asahi-alarm', 'core', 'extra', 'alarm', 'aur'])
        self.assertTrue(all(url.startswith('https://') for url in check.UPSTREAM.values()))


